const escapeRegExp = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** 긴 조각이 앞에 와야 먼저 걸린다. 짧은 조각이 긴 조각을 잘라먹으면 뜻이 달라진다. */
const MATCHER = new RegExp(
  Object.keys(DICT)
    .sort((a, b) => b.length - a.length)
    .map(escapeRegExp)
    .join('|'),
  'g',
);

/** 받침이 있으면 「과」, 없으면 「와」. 이것만 틀려도 바로 어색하게 읽힌다. */
const withAnd = (word: string) => {
  const code = word.charCodeAt(word.length - 1);
  const korean = code >= 0xac00 && code <= 0xd7a3;
  return korean && (code - 0xac00) % 28 !== 0 ? '과' : '와';
};

/**
 * 조각을 바꾸고 나면 일본어 조사만 사이에 남는다.
 * 앞이 이미 한국어로 바뀐 자리에서만 손대야 원문 단어를 잘라먹지 않는다.
 */
const PARTICLES: [RegExp, string | ((...args: string[]) => string)][] = [
  [/([가-힣])\s*と\s*/g, (_m, before: string) => `${before}${withAnd(before)} `],
  [/([가-힣)\]])\s*[なのが]\s*/g, '$1 '],
  [/\s+(풍|씨)/g, '$1'],
];

/** 조각을 바꾸면 띄어쓰기와 괄호가 어긋난다. 한국어로 읽히게 정리한다. */
const tidy = (text: string) =>
  text
    .replace(/[（]/g, ' (')
    .replace(/[）]/g, ') ')
    .replace(/[【]/g, ' [')
    .replace(/[】]/g, '] ')
    .replace(/[・･]{2,}/g, '…')
    .replace(/[・･]/g, '·')
    .replace(/[＆]/g, '&')
    .replace(/、/g, ', ')
    .replace(/[。]/g, '. ')
    .replace(/\.{2,}/g, '…')
    .replace(/\s+/g, ' ')
    .replace(/\s*·\s*/g, ' · ')
    .replace(/\s+([)\],.])/g, '$1')
    .replace(/([([])\s+/g, '$1')
    .replace(/\(\s*\)|\[\s*\]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();

/**
 * 일본어 상품명을 읽을 수 있는 한국어로 바꾼다.
 * 바꿀 조각이 하나도 없으면 원문을 그대로 돌려준다.
 */
export function koreanName(name: string): string {
  let text = name;
  for (const [pattern, replacement] of PATTERNS) text = text.replace(pattern, replacement as string);
  text = text.replace(MATCHER, (match) => ` ${DICT[match]} `);
  for (const [pattern, replacement] of PARTICLES) text = text.replace(pattern, replacement as string);
  return tidy(text) || name;
}

